#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_static_key_has_both_translations() {
        for key in TextKey::ALL {
            assert!(
                !text(Locale::En, *key).trim().is_empty(),
                "missing EN: {key:?}"
            );
            assert!(
                !text(Locale::ZhCn, *key).trim().is_empty(),
                "missing ZH: {key:?}"
            );
        }
    }

    #[test]
    fn representative_copy_is_localized_without_translating_product_terms() {
        assert_eq!(text(Locale::En, TextKey::MenuFile), "File");
        assert_eq!(text(Locale::ZhCn, TextKey::MenuFile), "文件");
        assert_eq!(text(Locale::En, TextKey::SettingsAppearance), "Appearance");
        assert_eq!(text(Locale::ZhCn, TextKey::SettingsAppearance), "外观");
        assert_eq!(text(Locale::En, TextKey::AdapterFim), "FIM");
        assert_eq!(text(Locale::ZhCn, TextKey::AdapterFim), "FIM");
        assert_eq!(text(Locale::ZhCn, TextKey::LanguageEnglish), "English");
        assert_eq!(text(Locale::En, TextKey::LanguageZhCn), "简体中文");
    }

    #[test]
    fn dynamic_counts_follow_locale_grammar() {
        assert_eq!(find_match_count(Locale::En, 2, 7), "2 of 7");
        assert_eq!(find_match_count(Locale::ZhCn, 2, 7), "第 2 项，共 7 项");
        assert_eq!(known_models_count(Locale::En, 1), "1 known model");
        assert_eq!(known_models_count(Locale::En, 2), "2 known models");
        assert_eq!(known_models_count(Locale::ZhCn, 2), "2 个已知模型");
    }

    #[test]
    fn only_generated_untitled_names_are_localized() {
        assert_eq!(
            localized_document_name(Locale::ZhCn, "Untitled-3", false),
            "无标题-3"
        );
        assert_eq!(
            localized_document_name(Locale::En, "Untitled-3", false),
            "Untitled-3"
        );
        assert_eq!(
            localized_document_name(Locale::ZhCn, "Untitled-3", true),
            "Untitled-3"
        );
        assert_eq!(
            localized_document_name(Locale::ZhCn, "main.rs", false),
            "main.rs"
        );
    }
}
