pub fn text(locale: Locale, key: TextKey) -> &'static str {
    match locale {
        Locale::En => english(key),
        Locale::ZhCn => simplified_chinese(key),
    }
}

pub fn find_match_count(locale: Locale, current: usize, total: usize) -> String {
    match locale {
        Locale::En => format!("{current} of {total}"),
        Locale::ZhCn => format!("第 {current} 项，共 {total} 项"),
    }
}

pub fn known_models_count(locale: Locale, count: usize) -> String {
    match locale {
        Locale::En if count == 1 => "1 known model".into(),
        Locale::En => format!("{count} known models"),
        Locale::ZhCn => format!("{count} 个已知模型"),
    }
}

pub fn localized_document_name(locale: Locale, display_name: &str, has_path: bool) -> String {
    if !has_path {
        if let Some(number) = display_name.strip_prefix("Untitled-") {
            return format!("{}-{number}", text(locale, TextKey::UntitledDocument));
        }
    }
    display_name.to_owned()
}

